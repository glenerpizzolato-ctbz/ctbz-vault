#!/usr/bin/env python3
"""
Call the WhatsApp bot (Ultimate) company lookup routes through the atendimento API gateway (Kong), the same way the bot does.

Credentials (never printed):
1. AUTH_TOKEN comes from the environment variables of the `zendeskbot-config` Cloud Function (project contabilizei-crm / contabilizei-crm-dev), via `gcloud functions describe`.
2. `zendeskbot-config?auth_token=...` returns the gateway host and x-api-key (config.app.services.apigateway), the same config the Ultimate bot loads.
3. The gateway url and x-api-key are cached in the skill's Bruno collection `.env` (bruno/.env, gitignored), shared with the Bruno requests. When the gateway rejects the cached key (401/403 from Kong), it is fetched again and the cache is rewritten.

Routes (all read-only):
    telefone       plataforma-crm-web  POST .../atendimento/v2/bots/whatsapp/dados-cliente/buscar-por-telefone
    telefone-cnpj  plataforma-crm-web  POST .../atendimento/v2/bots/whatsapp/dados-cliente/buscar-por-telefone-e-cnpj
    autenticar     atendimento-zendesk POST .../api/v1/bots/whatsapp/autenticacao/basico-padrao

Usage:
    bots_api.py telefone [telefone] [--env prd|dev] [--raw]
    bots_api.py telefone-cnpj <telefone> <cnpj> [--env prd|dev] [--raw]
    bots_api.py autenticar <telefone> [--cnpj CNPJ | --cpf CPF] [--area CRM|BANK|EXPERT|ATIVACAO] [--env prd|dev] [--raw]
    bots_api.py credenciais [--env prd|dev|todos]   # refresh the cached gateway credentials (for Bruno)

When omitted in `telefone`, the phone defaults to DEFAULT_PHONE (Glener's). The phone may be given with or without +55 / formatting (e.g. 84981683157, +55 84 98168-3157).
"""

import argparse
import json
import re
import secrets
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

PROJECTS = {"prd": "contabilizei-crm", "dev": "contabilizei-crm-dev"}
CONFIG_FUNCTION = "zendeskbot-config"
REGION = "us-central1"
# Glener's own phone, used when no phone is given.
DEFAULT_PHONE = "+555596981032"
ENV_FILE = Path(__file__).resolve().parent.parent / "bruno" / ".env"
# The WAF in front of the gateway blocks library user agents such as Python-urllib (403 in HTML).
USER_AGENT = "curl/8.5.0"

PLATAFORMA_PATH = "/atendimento/zendesk/bots/whatsapp/plataforma/atendimento/v2/bots/whatsapp/dados-cliente"
AUTENTICACAO_PATH = "/atendimento/zendesk/bots/whatsapp/fluxo/interacao/api/v1/bots/whatsapp/autenticacao/basico-padrao"


def gcloud_function(env: str) -> tuple[str, str]:
    """Return (function url, AUTH_TOKEN) of zendeskbot-config, read from its deployed env vars."""
    cmd = [
        "gcloud", "functions", "describe", CONFIG_FUNCTION,
        "--project", PROJECTS[env], "--region", REGION, "--format=json",
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"gcloud functions describe failed (gcloud auth login?): {proc.stderr.strip()[:300]}")
    data = json.loads(proc.stdout)
    service = data.get("serviceConfig", {})
    url = service.get("uri") or data.get("url")
    token = (service.get("environmentVariables") or {}).get("AUTH_TOKEN")
    if not url or not token:
        sys.exit(f"{CONFIG_FUNCTION} in {PROJECTS[env]} has no uri/AUTH_TOKEN")
    return url, token


def http(method: str, url: str, headers: dict, body: dict | None = None) -> tuple[int, dict | str]:
    data = json.dumps(body).encode() if body is not None else None
    all_headers = {"Content-Type": "application/json", "User-Agent": USER_AGENT, **headers}
    req = urllib.request.Request(url, data=data, method=method, headers=all_headers)
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            status, raw = resp.status, resp.read().decode()
    except urllib.error.HTTPError as e:
        status, raw = e.code, e.read().decode()
    try:
        return status, json.loads(raw)
    except json.JSONDecodeError:
        return status, raw


def read_cache() -> dict:
    cache = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                key, value = line.split("=", 1)
                cache[key.strip()] = value.strip().strip('"').strip("'")
    return cache


def write_cache(cache: dict) -> None:
    ENV_FILE.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by scripts/bots_api.py (zendeskbot-config). Gitignored: never commit."]
    lines += [f"{key}={value}" for key, value in sorted(cache.items())]
    ENV_FILE.write_text("\n".join(lines) + "\n")
    ENV_FILE.chmod(0o600)


def fetch_credentials(env: str) -> tuple[str, str]:
    """Fetch (gateway base url, x-api-key) from zendeskbot-config and cache them."""
    fn_url, auth_token = gcloud_function(env)
    status, body = http("GET", f"{fn_url}?auth_token={auth_token}", {})
    if status != 200 or not isinstance(body, dict):
        sys.exit(f"{CONFIG_FUNCTION} returned {status}")
    apigateway = body["config"]["app"]["services"]["apigateway"]
    host = apigateway["url"]
    base_url = host if host.startswith("http") else f"https://{host}"
    cache = read_cache()
    cache[f"api_gateway_url_{env}"] = base_url
    cache[f"api_gateway_token_{env}"] = apigateway["token"]
    write_cache(cache)
    return base_url, apigateway["token"]


def credentials(env: str, refresh: bool = False) -> tuple[str, str]:
    cache = read_cache()
    url, token = cache.get(f"api_gateway_url_{env}"), cache.get(f"api_gateway_token_{env}")
    if refresh or not url or not token:
        return fetch_credentials(env)
    return url, token


def gateway_headers(token: str) -> dict:
    # Kong requires these three headers; trace/atendimento ids only need a plausible format.
    return {
        "x-api-key": token,
        "x-cloud-trace-context": f"{secrets.token_hex(16)}/{secrets.randbelow(10**18)};o=1",
        "x-atendimento-id": secrets.token_hex(12),
        "x-conversation-id": "claude-skill",
    }


def call_gateway(env: str, path: str, body: dict) -> tuple[int, dict | str]:
    base_url, token = credentials(env)
    status, resp = http("POST", f"{base_url}{path}", gateway_headers(token), body)
    # Kong answers 401/403 in JSON when the key is invalid; a 403 in HTML is the WAF, not the key.
    if status in (401, 403) and isinstance(resp, dict):
        base_url, token = credentials(env, refresh=True)
        status, resp = http("POST", f"{base_url}{path}", gateway_headers(token), body)
    return status, resp


def normalize_phone(phone: str) -> str:
    digits = re.sub(r"\D", "", phone)
    if not digits.startswith("55") or len(digits) <= 11:
        digits = "55" + digits
    return "+" + digits


def normalize_doc(doc: str | None) -> str | None:
    return re.sub(r"\D", "", doc) if doc else None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--env", choices=[*PROJECTS, "todos"], default="prd")
    parser.add_argument("--raw", action="store_true", help="print the full JSON response")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_tel = sub.add_parser("telefone")
    p_tel.add_argument("telefone", nargs="?", default=DEFAULT_PHONE)

    p_tel_cnpj = sub.add_parser("telefone-cnpj")
    p_tel_cnpj.add_argument("telefone")
    p_tel_cnpj.add_argument("cnpj")

    p_auth = sub.add_parser("autenticar")
    p_auth.add_argument("telefone")
    p_auth.add_argument("--cnpj")
    p_auth.add_argument("--cpf")
    p_auth.add_argument("--area", default="CRM", choices=["CRM", "BANK", "EXPERT", "ATIVACAO"])

    p_cred = sub.add_parser("credenciais")

    for p in (p_tel, p_tel_cnpj, p_auth, p_cred):
        p.add_argument("--env", choices=[*PROJECTS, "todos"], default=argparse.SUPPRESS)
        p.add_argument("--raw", action="store_true", default=argparse.SUPPRESS)

    args = parser.parse_args()

    if args.cmd == "credenciais":
        envs = list(PROJECTS) if args.env == "todos" else [args.env]
        for env in envs:
            fetch_credentials(env)
            print(f"{env}: api_gateway_url_{env} / api_gateway_token_{env} updated in {ENV_FILE}")
        return
    if args.env == "todos":
        sys.exit("--env todos is only valid for 'credenciais'")

    telefone = normalize_phone(args.telefone)
    if args.cmd == "telefone":
        path, body = f"{PLATAFORMA_PATH}/buscar-por-telefone", {"telefone": telefone}
    elif args.cmd == "telefone-cnpj":
        path = f"{PLATAFORMA_PATH}/buscar-por-telefone-e-cnpj"
        body = {"telefone": telefone, "cnpj": normalize_doc(args.cnpj)}
    else:
        path, body = AUTENTICACAO_PATH, {"area": args.area, "telefone": telefone}
        if args.cnpj:
            body["cnpj"] = normalize_doc(args.cnpj)
        if args.cpf:
            body["cpf"] = normalize_doc(args.cpf)

    status, resp = call_gateway(args.env, path, body)
    print(f"# {args.env} {args.cmd} {json.dumps(body, ensure_ascii=False)} -> HTTP {status}", file=sys.stderr)
    if args.raw or not isinstance(resp, dict):
        print(json.dumps(resp, ensure_ascii=False, indent=2) if isinstance(resp, dict) else resp)
    else:
        print(json.dumps(resp.get("data", resp), ensure_ascii=False, indent=2))
    sys.exit(0 if status < 400 else 1)


if __name__ == "__main__":
    main()
